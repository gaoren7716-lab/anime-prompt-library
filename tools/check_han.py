# -*- coding: utf-8 -*-
"""扫描 JS 中的繁体 / 日式汉字泄漏。
用法: python tools/check_han.py assets/lib-*.js
只检查中文环境里该用简化字却写成繁体的常见字形。
"""
import re
import sys

# 常见繁体 / 日式汉字 -> 建议的简体写法
TRAD = list("動畫專對應該這麼樣設計製作處理發現標準關係當為與於線畫網"
            "體個們來時後進業開發點無學術產影響實現價格義發東具體"
            "選擇參與場所構築言語記憶錄层级還這種說話讀寫")

SIMPLIFIED_HINT = {
    "動": "动", "畫": "画", "專": "专", "對": "对", "應": "应", "該": "该",
    "這麼": "这么", "樣": "样", "設": "设", "計": "计", "製": "制", "處": "处",
    "發": "发", "現": "现", "標": "标", "準": "准", "關": "关", "係": "系",
    "當": "当", "為": "为", "與": "与", "於": "于", "線": "线", "網": "网",
    "體": "体", "個": "个", "們": "们", "來": "来", "時": "时", "後": "后",
    "進": "进", "業": "业", "開": "开", "點": "点", "無": "无", "學": "学",
    "術": "术", "產": "产", "響": "响", "價": "价", "義": "义",
    "東": "东", "選": "选", "擇": "择", "參": "参", "場": "场",
    # 注意：格 / 所 / 板 / 面 / 白 等简繁同形，不要列入本表，否则全是误报
    "構": "构", "築": "筑", "語": "语", "憶": "忆", "錄": "录", "還": "还",
    "說": "说", "讀": "读", "寫": "写", "層": "层", "級": "级",
}

TOTAL = 0
for path in sys.argv[1:]:
    with open(path, "r", encoding="utf-8") as f:
        lines = f.readlines()
    hits = []
    for i, ln in enumerate(lines, 1):
        for ch in set(ln):
            if ch in SIMPLIFIED_HINT:
                hits.append((i, ch, SIMPLIFIED_HINT[ch], ln.strip()[:80]))
    if hits:
        print("==== %s : %d 处 ====" % (path.split("\\")[-1], len(hits)))
        for i, ch, rep, raw in sorted(hits):
            print("  L%-4d %s -> %s   | %s" % (i, ch, rep, raw))
    else:
        print("==== %s : 0 处 ====" % path.split("\\")[-1])
    TOTAL += len(hits)

print("\n繁体泄漏合计：%d 处" % TOTAL)
