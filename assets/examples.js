/* ============================================================
 * 示例画廊 · 数据
 * 每条 = { id, img, note }：
 *   id   —— 与条目编码一致（A1-01 等），运行时经 ENGINE.collectEntries()
 *           与 PROMPT_SETS 反查标题与正文，**不在这里复制正文**：
 *           正文唯一真源在 data-prompts-*.js，复制一份必然漂移。
 *   img  —— 相对 index.html 的图片路径（examples/<id>.png）。
 *   note —— 「看点」：这张图实际验证了该条目的哪几个特征词。
 *           写的是图上真看得见的东西，不写条目宣传语 ——
 *           第一版画出来的厚涂其实笔触很薄，那条「看点」当时就是在
 *           声称图没验证的东西，等于给假证据。
 *
 * 两条硬约定（都是被真 bug 逼出来的）：
 *
 * 1. **图由「GPT 正文」生成，不是由 demo 标签串生成。**
 *    库里 demo（标签速用版）与 gpt（自然语言正文）是两份独立文案，
 *    主体经常不同：demo 写「chibi catgirl」正文写「举冰淇淋的猫耳少女」，
 *    demo 写「lone swordsman」正文写「拔刀瞬间的剑客」。
 *    画廊把两者并排展示还说「图由 demo 生成」，等于用一张图同时
 *    证明两件不同的事——用户复制正文出图，拿到的画面和画廊不一样。
 *    所以：**图 = 正文的效果快照**，标签版只是另一口径的备选写法。
 *
 * 2. **出图时必须把正文里的禁止项一起喂给模型**（no text / no letters）。
 *    正文写了「no text」但标签串里没有，模型就会自由发挥写出招牌字、
 *    标题字、pose 标注字——实测 12 张里出了 4 张这种废图。
 *    这也是 prompt-kit.js 的 NEG_BASE 必须含 text/letters 的原因：
 *    标签版路径同样需要文字抑制词，否则约束根本不参与。
 *
 * 图片全部为 R0 条目——画廊是库的门面，只放可自由商用的内容。
 *
 * ============================================================
 * 【补图的操作约定（第二批配图时踩出来的）】
 * ============================================================
 *
 * 1. **文件名用旧 id**（A1-02.png），不用规范码。
 *    旧 id 永久可解析到规范码（code-map.js 登记了四种写法），
 *    所以图与词条的对应关系不会因重排而错位。
 *
 * 2. **扩展名不统一**：出图通道的原生格式是什么就用什么。
 *    免 key 通道（Sana）回 jpg，早前那批 PNG 是别处生成的。
 *    强行统一成 png 只会逼人多做一次掉质量的转码。
 *    ui_test 的路径断言接受 png/jpg/webp/avif。
 *
 * 3. **题材要挑对，画风才立得住。**
 *    实测：`A1-06 半写实/真人向动画` 配`TH-005 军事战争`，
 *    出来的是写实末世照——风格被题材整个盖掉。
 *    换 `TH-012`（人物）才对。
 *    所以**配图失败多数不是画风写错了，是题材压过了画风**。
 *
 * 4. **废图直接删，不进画廊。**
 *    试过给A1-02 配图时出来一张装裱圆盘的相框、正中还有个「X」字母，
 *    而且右下角带通道水印。当时若留下并写一条"看点"，
 *    就等于给假证据——`note`写的是图上真看得见的东西。
 *
 * 5. **水印要写进note。**
 *    免 key 通道的图必带 pollinations 水印，商用前要裁。
 *    这一条必须写在 note 里，不能指望用户自己发现。
 *
 * 6. **配图之前先查授权，而且必须用 `RIGHTS.inspect()`，不能用 `tierOf()`。**
 *    实测：`A1-06 半写实/真人向动画` 用 `tierOf()` 查是 **R0**，
 *    但 `inspect()` 查出 **R2** —— 它的 desc 里写了在世创作者「今敏」。
 *    `tierOf()` 只做文本扫描，认不出描述字段里的受保护标识。
 *    于是配好图登记进画廊，`check_rights` 第 10c组当场变红。
 *    图本身没问题（画得对），是**条目不满足 R0**，
 *    所以是撤图而不是撤断言。
 *    这也是第 10c 组存在的理由：画廊是门面，摆一张需要署名的图
 *    就是把授权问题直接递到用户面前。
 *
 * 7. **「先登记提示词、后补图」的条目 img 写 null。**
 *    画廊从 13 张扩到 50 条时引入的形态：提示词已就绪、可复制即用，
 *    图后续补。约定：
 *      - img: null  —— 一切消费方（网页卡 / README 嵌入 / 体检脚本）
 *        都以 `g.img` 真值为准区分两种卡，不另设 status 字段
 *        （多一个字段就多一处漂移可能）。
 *      - note 以「待配图 · 验证点：」开头 —— 写的是**未来这张图
 *        必须演示什么**，不是图上看得见的东西。已配图的卡写「看点」，
 *        是图上真看得见的；两者的措辞边界不能混。
 *      - 补图时：把 img 改成 "examples/<id>.<png|jpg>"，
 *        把 note 从「待配图 · 验证点」改写成「看点」。
 * ============================================================ */

